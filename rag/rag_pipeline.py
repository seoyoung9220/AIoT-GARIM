import json

from .retriever import search_policy


# ============================================================
# 개인정보 유형 한글 매핑
# ============================================================

PII_LABELS = {
    "name": "이름 성명",
    "phone": "전화번호 연락처",
    "address": "주소",
    "resident_no": "주민등록번호",
    "business_no": "사업자등록번호",
    "account": "계좌번호"
}


# ============================================================
# 공유 대상 한글 매핑
# ============================================================

TARGET_LABELS = {
    "internal": "사내 내부 이용",
    "partner": "협력사 제3자 제공",
    "public": "외부 공개 배포"
}


# ============================================================
# RAG Pipeline
# ============================================================

def run_rag(
    pii_type,
    target,
    value=None
):
    """
    개인정보 유형과 공유 대상을 기반으로
    사내정책 + 공식자료를 검색한다.

    Parameters
    ----------
    pii_type : str
        name
        phone
        address
        resident_no
        business_no
        account

    target : str
        internal
        partner
        public

    value : str | None
        실제 탐지된 개인정보 값.
        현재 검색에는 직접 사용하지 않는다.

    Returns
    -------
    dict
        LLM에 전달 가능한 RAG 결과
    """

    # --------------------------------------------------------
    # 영문 코드 → 한글 검색어 변환
    # --------------------------------------------------------

    pii_label = PII_LABELS.get(
        pii_type,
        pii_type
    )

    target_label = TARGET_LABELS.get(
        target,
        target
    )

    # --------------------------------------------------------
    # 공식자료 검색용 Query 생성
    # --------------------------------------------------------

    query = (
        f"{pii_label} 개인정보를 "
        f"{target_label} 목적으로 제공하거나 공유할 때 "
        f"개인정보 처리 보호 비식별화 마스킹 관련 기준"
    )

    # --------------------------------------------------------
    # RAG 검색
    # --------------------------------------------------------

    rag_result = search_policy(
        query=query,
        pii_type=pii_type,
        target=target,

        # 검색 품질 확인을 위해 우선 Top-5
        official_top_k=5
    )

    # --------------------------------------------------------
    # LLM 전달용 최종 결과
    # --------------------------------------------------------

    return {
        "pii_type": pii_type,
        "target": target,
        "rag_results": rag_result
    }


# ============================================================
# 테스트
# ============================================================

if __name__ == "__main__":

    # --------------------------------------------------------
    # 테스트 조건
    #
    # 전화번호 + 협력사 공유
    # --------------------------------------------------------

    result = run_rag(
        pii_type="phone",
        target="partner",
        value="010-1234-5678"
    )

    print()
    print("=" * 60)
    print("RAG Pipeline 최종 결과")
    print("=" * 60)

    print(
        json.dumps(
            result,
            ensure_ascii=False,
            indent=2
        )
    )
